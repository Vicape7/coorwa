#![allow(unexpected_cfgs)]
//! Coorwa launch curve.
//!
//! A launch here is one token, one curve and one tax. The program mints a Token-2022 token whose
//! transfer fee is chosen by the creator and then frozen forever, sells it against COOK on a
//! constant-product curve with virtual reserves, and at a fixed amount raised hands the token to a
//! real pool. The tax is what pays the token's holders, so it has to be live from the very first
//! trade: that is the whole reason a buy here moves real tokens instead of a program-side balance.
//!
//! Three properties are load bearing, and each one is a thing a buyer can check on chain rather
//! than a promise on a web page:
//!
//!   - **The tax can never change.** `transfer_fee_config_authority` is set to `None` at the moment
//!     the mint is created, not renounced later, so there is no window in which anyone could raise
//!     it. The rate a launch opens with is the rate it dies with.
//!   - **The supply is fixed and the mint is sealed.** The whole supply is minted once, in the same
//!     instruction, and the mint authority is dropped before the instruction returns. There is no
//!     freeze authority and no permanent delegate, so nobody can mint, freeze or seize.
//!   - **The curve cannot be drained.** Quote only ever leaves through `sell`, priced by the same
//!     invariant that let it in, and the fees the program keeps are tracked separately from the
//!     reserve so that claiming them can never eat into what sellers are owed.
//!
//! What the program deliberately does *not* do: hold anyone's tokens for them. There is no claim
//! step. A buy delivers the token to the buyer's own account in the same transaction, which is what
//! makes the tax collectible from the first trade and also means a curve that never graduates still
//! paid its holders along the way.
//!
//! ## Why the sell path reads a balance instead of doing arithmetic
//!
//! Every transfer of a taxed mint arrives short: the fee is withheld in the destination account, so
//! when a seller sends the curve 1,000 tokens the vault's spendable balance goes up by less. The
//! amount the curve must price is the amount that actually arrived, and the only source of truth
//! for that is the vault itself. So `sell` reloads the vault and prices the trade off the delta.
//! Recomputing the fee from the mint's config would give the same answer today and a wrong answer
//! the day anything about that config surprises us.
//!
//! Buys need no such care. The base leaving the vault is taxed too, but the fee is withheld in the
//! *buyer's* account, so the vault's side of the arithmetic is exact and the buyer simply receives
//! the rate less than the curve sent. The client shows that, and `min_base_out` is checked against
//! what the curve sends, not against what the buyer nets.

