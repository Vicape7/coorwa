#[error_code]
pub enum LaunchError {
    #[msg("arithmetic overflowed")]
    MathOverflow,
    #[msg("a config value is out of range")]
    BadConfig,
    #[msg("launches are paused")]
    LaunchesPaused,
    #[msg("that tax rate is not one of the offered tiers")]
    TaxTierNotOffered,
    #[msg("name, symbol or uri is empty or too long")]
    BadMetadata,
    #[msg("this curve is closed to trading")]
    CurveClosed,
    #[msg("amount must be greater than zero")]
    ZeroAmount,
    #[msg("the amount is too small to move anything")]
    AmountTooSmall,
    #[msg("the curve has no base left to sell")]
    CurveExhausted,
    #[msg("the trade would return less than you asked for")]
    SlippageExceeded,
    #[msg("the curve cannot pay out more quote than it holds")]
    CurveInsolvent,
    #[msg("there is nothing to claim")]
    NothingToClaim,
}
