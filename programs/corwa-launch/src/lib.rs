// --- mint creation -------------------------------------------------------------------------------

/// Build the mint by hand, because Anchor cannot.
///
/// `#[account(init, mint::..)]` sizes the account for a bare mint, and extension space has to be
/// allocated before `initialize_mint2` runs. So the account is created here at the right length, the
/// two extensions are initialized into it, and only then does it become a mint.
///
/// The order is not cosmetic: the transfer fee goes in first with no config authority at all, so
/// there is never a moment, not even within this instruction, when the rate could be changed.
fn create_taxed_mint(ctx: &Context<Launch>, tax_bps: u16) -> Result<()> {
    let space = spl_token_2022::extension::ExtensionType::try_calculate_account_len::<
        spl_token_2022::state::Mint,
    >(&[
        spl_token_2022::extension::ExtensionType::TransferFeeConfig,
        spl_token_2022::extension::ExtensionType::MetadataPointer,
    ])?;
    let lamports = Rent::get()?.minimum_balance(space);

    system_program::create_account(
        CpiContext::new(
            ctx.accounts.system_program.to_account_info(),
            system_program::CreateAccount {
                from: ctx.accounts.creator.to_account_info(),
                to: ctx.accounts.mint.to_account_info(),
            },
        ),
        lamports,
        space as u64,
        &spl_token_2022::ID,
    )?;

    invoke(
        &spl_token_2022::extension::transfer_fee::instruction::initialize_transfer_fee_config(
            &spl_token_2022::ID,
            &ctx.accounts.mint.key(),
            None,
            Some(&ctx.accounts.config.withhold_authority),
            tax_bps,
            MAX_TRANSFER_FEE,
        )?,
        &[ctx.accounts.mint.to_account_info()],
    )?;

    invoke(
        &spl_token_2022::extension::metadata_pointer::instruction::initialize(
            &spl_token_2022::ID,
            &ctx.accounts.mint.key(),
            None,
            Some(ctx.accounts.mint.key()),
        )?,
        &[ctx.accounts.mint.to_account_info()],
    )?;

    invoke(
        &spl_token_2022::instruction::initialize_mint2(
            &spl_token_2022::ID,
            &ctx.accounts.mint.key(),
            &ctx.accounts.curve.key(),
            None,
            ctx.accounts.config.token_decimals,
        )?,
        &[ctx.accounts.mint.to_account_info()],
    )?;

    Ok(())
}

/// Write the name, symbol and link into the mint itself, then pay for the space that took.
///
/// The update authority is the curve, and the program has no instruction that uses it, so the
/// metadata is immutable in practice. That is deliberate: a token that can be renamed after people
/// have bought it is a token that can be turned into something else.
fn write_metadata(ctx: &Context<Launch>, params: &LaunchParams, seeds: &[&[u8]]) -> Result<()> {
    token_interface::token_metadata_initialize(
        CpiContext::new_with_signer(
            ctx.accounts.token_program.to_account_info(),
            TokenMetadataInitialize {
                program_id: ctx.accounts.token_program.to_account_info(),
                mint: ctx.accounts.mint.to_account_info(),
                metadata: ctx.accounts.mint.to_account_info(),
                mint_authority: ctx.accounts.curve.to_account_info(),
                update_authority: ctx.accounts.curve.to_account_info(),
            },
            &[seeds],
        ),
        params.name.clone(),
        params.symbol.clone(),
        params.uri.clone(),
    )?;

    // The instruction above reallocs the mint, and a reallocated account still has to be rent
    // exempt.
    let mint = ctx.accounts.mint.to_account_info();
    let needed = Rent::get()?.minimum_balance(mint.data_len());
    let short = needed.saturating_sub(mint.get_lamports());
    if short > 0 {
        system_program::transfer(
            CpiContext::new(
                ctx.accounts.system_program.to_account_info(),
                system_program::Transfer {
                    from: ctx.accounts.creator.to_account_info(),
                    to: mint,
                },
            ),
            short,
        )?;
    }
    Ok(())
}

/// The curve's two token accounts. Created here rather than by a constraint, because the base mint
/// does not exist yet when Anchor resolves constraints.
fn open_vaults(ctx: &Context<Launch>) -> Result<()> {
    anchor_spl::associated_token::create(CpiContext::new(
        ctx.accounts.associated_token_program.to_account_info(),
        anchor_spl::associated_token::Create {
            payer: ctx.accounts.creator.to_account_info(),
            associated_token: ctx.accounts.base_vault.to_account_info(),
            authority: ctx.accounts.curve.to_account_info(),
            mint: ctx.accounts.mint.to_account_info(),
            system_program: ctx.accounts.system_program.to_account_info(),
            token_program: ctx.accounts.token_program.to_account_info(),
        },
    ))?;

    anchor_spl::associated_token::create(CpiContext::new(
        ctx.accounts.associated_token_program.to_account_info(),
        anchor_spl::associated_token::Create {
            payer: ctx.accounts.creator.to_account_info(),
            associated_token: ctx.accounts.quote_vault.to_account_info(),
            authority: ctx.accounts.curve.to_account_info(),
            mint: ctx.accounts.quote_mint.to_account_info(),
            system_program: ctx.accounts.system_program.to_account_info(),
            token_program: ctx.accounts.quote_token_program.to_account_info(),
        },
    ))?;
    Ok(())
}

/// Mint the whole supply into the curve, then throw the key away.
fn mint_supply_and_seal(ctx: &Context<Launch>, supply: u64, seeds: &[&[u8]]) -> Result<()> {
    token_interface::mint_to(
        CpiContext::new_with_signer(
            ctx.accounts.token_program.to_account_info(),
            token_interface::MintTo {
                mint: ctx.accounts.mint.to_account_info(),
                to: ctx.accounts.base_vault.to_account_info(),
                authority: ctx.accounts.curve.to_account_info(),
            },
            &[seeds],
        ),
        supply,
    )?;

    token_interface::set_authority(
        CpiContext::new_with_signer(
            ctx.accounts.token_program.to_account_info(),
            token_interface::SetAuthority {
                current_authority: ctx.accounts.curve.to_account_info(),
                account_or_mint: ctx.accounts.mint.to_account_info(),
            },
            &[seeds],
        ),
        spl_token_2022::instruction::AuthorityType::MintTokens,
        None,
    )?;
    Ok(())
}

