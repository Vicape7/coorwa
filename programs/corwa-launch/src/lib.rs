#[program]
pub mod corwa_launch {
    use super::*;

    /// Create the one config every launch reads. Whoever signs this owns the platform settings.
    pub fn initialize_config(ctx: Context<InitializeConfig>, params: ConfigParams) -> Result<()> {
        params.validate()?;

        let config = &mut ctx.accounts.config;
        config.authority = ctx.accounts.authority.key();
        config.quote_mint = ctx.accounts.quote_mint.key();
        config.bump = ctx.bumps.config;
        config.launch_count = 0;
        params.apply(config);

        emit!(ConfigInitialized {
            config: config.key(),
            authority: config.authority,
            quote_mint: config.quote_mint,
        });
        Ok(())
    }

    /// Change the settings future launches will read.
    ///
    /// A live curve is untouched by this on purpose: every number that prices a trade is copied
    /// onto the curve when it is created, so nobody's launch can be repriced under them.
    pub fn update_config(ctx: Context<UpdateConfig>, params: ConfigParams) -> Result<()> {
        params.validate()?;
        params.apply(&mut ctx.accounts.config);

        emit!(ConfigUpdated { config: ctx.accounts.config.key() });
        Ok(())
    }

    /// Mint a launch token and open its curve.
    ///
    /// Everything irreversible about the token happens here: the extensions it will carry, the tax
    /// it will charge, its whole supply, and the loss of the mint authority. Nothing later in the
    /// program's life can add to that list.
    pub fn launch(ctx: Context<Launch>, params: LaunchParams) -> Result<()> {
        let config = &ctx.accounts.config;
        require!(!config.paused, LaunchError::LaunchesPaused);
        require!(config.tax_allowed(params.tax_bps), LaunchError::TaxTierNotOffered);
        require!(!params.name.is_empty() && params.name.len() <= 32, LaunchError::BadMetadata);
        require!(!params.symbol.is_empty() && params.symbol.len() <= 10, LaunchError::BadMetadata);
        require!(params.uri.len() <= 200, LaunchError::BadMetadata);

        let mint_key = ctx.accounts.mint.key();
        let curve_bump = ctx.bumps.curve;
        let seeds: &[&[u8]] = &[CURVE_SEED, mint_key.as_ref(), &[curve_bump]];

        create_taxed_mint(&ctx, params.tax_bps)?;
        write_metadata(&ctx, &params, seeds)?;
        open_vaults(&ctx)?;
        mint_supply_and_seal(&ctx, config.total_supply(), seeds)?;

        let curve = &mut ctx.accounts.curve;
        curve.config = config.key();
        curve.creator = ctx.accounts.creator.key();
        curve.mint = mint_key;
        curve.base_vault = ctx.accounts.base_vault.key();
        curve.quote_vault = ctx.accounts.quote_vault.key();
        curve.virtual_base = config.virtual_base;
        curve.virtual_quote = config.virtual_quote;
        curve.sale_base = config.sale_base;
        curve.migration_base = config.migration_base;
        curve.graduation_quote = config.graduation_quote;
        curve.base_sold = 0;
        curve.quote_raised = 0;
        curve.fees_quote = 0;
        curve.tax_bps = params.tax_bps;
        curve.curve_fee_bps = config.curve_fee_bps;
        curve.creator_lp_share_bps = config.creator_lp_share_bps;
        curve.state = STATE_LIVE;
        curve.created_at = Clock::get()?.unix_timestamp;
        curve.bump = curve_bump;

        let config = &mut ctx.accounts.config;
        config.launch_count = config.launch_count.saturating_add(1);

        emit!(Launched {
            curve: ctx.accounts.curve.key(),
            mint: mint_key,
            creator: ctx.accounts.creator.key(),
            tax_bps: params.tax_bps,
            symbol: params.symbol,
        });
        Ok(())
    }

    /// Buy base with quote.
    ///
    /// `max_quote_in` is a ceiling rather than an amount. A curve that is close to its threshold
    /// takes only what it has room for and leaves the rest in the buyer's account, which is how the
    /// raise lands on the threshold exactly instead of overshooting it and needing a refund path.
    pub fn buy(ctx: Context<Trade>, max_quote_in: u64, min_base_out: u64) -> Result<()> {
        let curve = &ctx.accounts.curve;
        require!(curve.state == STATE_LIVE, LaunchError::CurveClosed);
        require!(max_quote_in > 0, LaunchError::ZeroAmount);

        let room = curve
            .graduation_quote
            .checked_sub(curve.quote_raised)
            .ok_or(LaunchError::MathOverflow)?;
        require!(room > 0, LaunchError::CurveClosed);

        let mint_key = curve.mint;
        let authority_bump = ctx.bumps.vault_authority;

        let (quote_taken, fee, net) = math::split_buy(max_quote_in, curve.curve_fee_bps, room)?;
        require!(net > 0, LaunchError::AmountTooSmall);

        let base_out = math::swap_out(curve.reserve_base()?, curve.reserve_quote()?, net as u128)?;
        let base_out = u64::try_from(base_out).map_err(|_| LaunchError::MathOverflow)?;
        require!(base_out >= min_base_out, LaunchError::SlippageExceeded);
        require!(base_out > 0, LaunchError::AmountTooSmall);

        let unsold = curve
            .sale_base
            .checked_sub(curve.base_sold)
            .ok_or(LaunchError::MathOverflow)?;
        require!(base_out <= unsold, LaunchError::CurveExhausted);

        // Quote in first: if the buyer cannot pay, nothing else should have happened.
        token_interface::transfer_checked(
            ctx.accounts.quote_in_ctx(),
            quote_taken,
            ctx.accounts.quote_mint.decimals,
        )?;

        let seeds: &[&[u8]] = &[AUTHORITY_SEED, mint_key.as_ref(), &[authority_bump]];
        let signer: &[&[&[u8]]] = &[seeds];
        token_interface::transfer_checked(
            ctx.accounts.base_out_ctx(signer),
            base_out,
            ctx.accounts.mint.decimals,
        )?;

        let curve = &mut ctx.accounts.curve;
        curve.quote_raised = curve.quote_raised.saturating_add(net);
        curve.fees_quote = curve.fees_quote.saturating_add(fee);
        curve.base_sold = curve.base_sold.saturating_add(base_out);
        if curve.quote_raised >= curve.graduation_quote {
            curve.state = STATE_GRADUATED;
        }

        emit!(Traded {
            curve: curve.key(),
            mint: curve.mint,
            trader: ctx.accounts.trader.key(),
            is_buy: true,
            quote_amount: quote_taken,
            base_amount: base_out,
            fee,
            quote_raised: curve.quote_raised,
            base_sold: curve.base_sold,
            graduated: curve.state == STATE_GRADUATED,
        });
        Ok(())
    }

    /// Sell base back to the curve.
    ///
    /// The tax is charged on the way in, so the curve prices what the vault actually received. A
    /// seller therefore pays the tax once, in the token, and again never: `min_quote_out` is checked
    /// against the quote they will really see.
    pub fn sell(ctx: Context<Trade>, base_in: u64, min_quote_out: u64) -> Result<()> {
        let curve = &ctx.accounts.curve;
        require!(curve.state == STATE_LIVE, LaunchError::CurveClosed);
        require!(base_in > 0, LaunchError::ZeroAmount);

        let before = ctx.accounts.base_vault.amount;
        token_interface::transfer_checked(
            ctx.accounts.base_in_ctx(),
            base_in,
            ctx.accounts.mint.decimals,
        )?;
        ctx.accounts.base_vault.reload()?;
        let received = ctx
            .accounts
            .base_vault
            .amount
            .checked_sub(before)
            .ok_or(LaunchError::MathOverflow)?;
        require!(received > 0, LaunchError::AmountTooSmall);

        let curve = &ctx.accounts.curve;
        let mint_key = curve.mint;
        let authority_bump = ctx.bumps.vault_authority;
        let gross = math::swap_out(curve.reserve_quote()?, curve.reserve_base()?, received as u128)?;
        let gross = u64::try_from(gross).map_err(|_| LaunchError::MathOverflow)?;
        require!(gross > 0, LaunchError::AmountTooSmall);
        require!(gross <= curve.quote_raised, LaunchError::CurveInsolvent);

        let fee = math::bps_of(gross, curve.curve_fee_bps)?;
        let to_seller = gross.checked_sub(fee).ok_or(LaunchError::MathOverflow)?;
        require!(to_seller >= min_quote_out, LaunchError::SlippageExceeded);

        let seeds: &[&[u8]] = &[AUTHORITY_SEED, mint_key.as_ref(), &[authority_bump]];
        let signer: &[&[&[u8]]] = &[seeds];
        token_interface::transfer_checked(
            ctx.accounts.quote_out_ctx(signer),
            to_seller,
            ctx.accounts.quote_mint.decimals,
        )?;

        let curve = &mut ctx.accounts.curve;
        curve.quote_raised = curve.quote_raised.saturating_sub(gross);
        curve.fees_quote = curve.fees_quote.saturating_add(fee);
        curve.base_sold = curve
            .base_sold
            .checked_sub(received)
            .ok_or(LaunchError::MathOverflow)?;

        emit!(Traded {
            curve: curve.key(),
            mint: curve.mint,
            trader: ctx.accounts.trader.key(),
            is_buy: false,
            quote_amount: to_seller,
            base_amount: received,
            fee,
            quote_raised: curve.quote_raised,
            base_sold: curve.base_sold,
            graduated: false,
        });
        Ok(())
    }

    /// Send the curve fees collected so far to the config's fee recipient.
    ///
    /// Permissionless, because the destination is fixed by the config rather than by whoever calls,
    /// and a lost operator key should not strand the platform's own revenue.
    pub fn claim_curve_fees(ctx: Context<ClaimCurveFees>) -> Result<()> {
        let curve = &ctx.accounts.curve;
        let amount = curve.fees_quote;
        require!(amount > 0, LaunchError::NothingToClaim);

        let mint_key = curve.mint;
        let seeds: &[&[u8]] = &[AUTHORITY_SEED, mint_key.as_ref(), &[ctx.bumps.vault_authority]];
        let signer: &[&[&[u8]]] = &[seeds];
        token_interface::transfer_checked(
            ctx.accounts.transfer_ctx(signer),
            amount,
            ctx.accounts.quote_mint.decimals,
        )?;

        let curve = &mut ctx.accounts.curve;
        curve.fees_quote = 0;

        emit!(FeesClaimed { curve: curve.key(), mint: curve.mint, amount });
        Ok(())
    }

    /// Open the token's pool on Cookiebox and lock the liquidity there forever.
    ///
    /// Permissionless, because a curve that has hit its target should not wait on us. Whoever sends
    /// it pays the rent for the pool accounts, which is why the vault authority needs lamports in it
    /// by the time this runs: a plain transfer in the same transaction is enough, and the crank that
    /// normally does this is ours.
    ///
    /// `liquidity` and `sqrt_price` are worked out by the caller, because reproducing the pool's own
    /// fixed-point liquidity maths here would cost more than it buys. What the program does instead
    /// is check the result: the price has to match the price the curve closed at, and the amounts the
    /// pool actually took have to match the reserve and the migration supply. A caller who passes
    /// bad numbers gets a failed transaction, not a bad pool.
    pub fn graduate(ctx: Context<Graduate>, liquidity: u128, sqrt_price: u128) -> Result<()> {
        let curve = &ctx.accounts.curve;
        require!(curve.state == STATE_GRADUATED, LaunchError::NotGraduated);
        require!(liquidity > 0, LaunchError::ZeroAmount);

        // The pool asks for the amount it wants to *hold* and the token program takes the tax on
        // top, so the base that reaches the pool is the migration supply less the tax. Pricing the
        // pool off the gross would ask the vault for more base than a fully sold curve has left.
        let seeded_base = math::net_of_tax(curve.migration_base, curve.tax_bps)?;
        let expected = math::expected_sqrt_price(curve.quote_raised, seeded_base)?;
        require!(math::within_one_percent(sqrt_price, expected), LaunchError::PriceMismatch);

        let mint_key = curve.mint;
        let authority_bump = ctx.bumps.vault_authority;
        let quote_raised = curve.quote_raised;
        let migration_base = curve.migration_base;

        let base_before = ctx.accounts.base_vault.amount;
        let quote_before = ctx.accounts.quote_vault.amount;

        let seeds: &[&[u8]] = &[AUTHORITY_SEED, mint_key.as_ref(), &[authority_bump]];
        ctx.accounts.initialize_pool(liquidity, sqrt_price, seeds)?;

        ctx.accounts.base_vault.reload()?;
        ctx.accounts.quote_vault.reload()?;
        let base_spent = base_before
            .checked_sub(ctx.accounts.base_vault.amount)
            .ok_or(LaunchError::MathOverflow)?;
        let quote_spent = quote_before
            .checked_sub(ctx.accounts.quote_vault.amount)
            .ok_or(LaunchError::MathOverflow)?;

        // The whole reserve goes into the pool, give or take the rounding the pool does on the way
        // in. Anything less would be liquidity quietly left behind.
        require!(quote_spent <= quote_raised, LaunchError::SeedOutOfRange);
        require!(
            (quote_spent as u128) * 1000 >= (quote_raised as u128) * 999,
            LaunchError::SeedOutOfRange
        );
        // What leaves the vault is the migration supply, tax included. A percent of slack covers the
        // rounding on both sides of that, and nothing covers a caller trying to seed the pool with
        // more of the supply than the launch set aside.
        let slack = migration_base / 100;
        require!(
            base_spent <= migration_base.saturating_add(slack),
            LaunchError::SeedOutOfRange
        );
        require!(
            base_spent >= migration_base.saturating_sub(slack.saturating_mul(2)),
            LaunchError::SeedOutOfRange
        );

        ctx.accounts.lock_liquidity(liquidity, seeds)?;

        // Everything the curve did not sell and the pool did not take is burned. A launch's supply
        // is what people actually hold plus what backs the pool, and nothing is kept in reserve for
        // anyone, including us.
        let leftover = ctx.accounts.base_vault.amount;
        if leftover > 0 {
            ctx.accounts.burn_leftover(leftover, seeds)?;
        }

        let curve = &mut ctx.accounts.curve;
        curve.state = STATE_POOLED;
        curve.position_nft_mint = ctx.accounts.position_nft_mint.key();

        emit!(Graduated {
            curve: curve.key(),
            mint: curve.mint,
            pool: ctx.accounts.pool.key(),
            position: ctx.accounts.position.key(),
            position_nft_mint: curve.position_nft_mint,
            quote_seeded: quote_spent,
            base_seeded: base_spent,
            burned: leftover,
            liquidity,
        });
        Ok(())
    }

    /// Collect the graduated pool's fees and split them.
    ///
    /// The position is locked forever, so this is the only thing it will ever produce. The split is
    /// enforced here rather than promised anywhere: the creator's share is paid in the same
    /// instruction that collects it, and neither we nor they can be paid without the other.
    ///
    /// Permissionless for the same reason as the curve fees: both destinations are fixed before the
    /// instruction runs.
    pub fn claim_pool_fees(ctx: Context<ClaimPoolFees>) -> Result<()> {
        let curve = &ctx.accounts.curve;
        require!(curve.state == STATE_POOLED, LaunchError::NotPooled);
        require!(
            curve.position_nft_mint == ctx.accounts.position_nft_mint.key(),
            LaunchError::WrongPosition
        );

        let mint_key = curve.mint;
        let authority_bump = ctx.bumps.vault_authority;
        let creator_share_bps = curve.creator_lp_share_bps;

        let base_before = ctx.accounts.base_vault.amount;
        let quote_before = ctx.accounts.quote_vault.amount;

        let seeds: &[&[u8]] = &[AUTHORITY_SEED, mint_key.as_ref(), &[authority_bump]];
        ctx.accounts.claim_position_fee(seeds)?;

        ctx.accounts.base_vault.reload()?;
        ctx.accounts.quote_vault.reload()?;
        let base_fees = ctx
            .accounts
            .base_vault
            .amount
            .checked_sub(base_before)
            .ok_or(LaunchError::MathOverflow)?;
        let quote_fees = ctx
            .accounts
            .quote_vault
            .amount
            .checked_sub(quote_before)
            .ok_or(LaunchError::MathOverflow)?;
        require!(base_fees > 0 || quote_fees > 0, LaunchError::NothingToClaim);

        // Only what this claim brought in is moved on, so a curve's own unclaimed trading fees and
        // any dust already sitting in the vaults are left where they are.
        let creator_quote = math::bps_of(quote_fees, creator_share_bps)?;
        let platform_quote = quote_fees
            .checked_sub(creator_quote)
            .ok_or(LaunchError::MathOverflow)?;
        let creator_base = math::bps_of(base_fees, creator_share_bps)?;
        let platform_base = base_fees
            .checked_sub(creator_base)
            .ok_or(LaunchError::MathOverflow)?;

        ctx.accounts.pay_out(creator_quote, platform_quote, creator_base, platform_base, seeds)?;

        emit!(PoolFeesClaimed {
            curve: ctx.accounts.curve.key(),
            mint: mint_key,
            quote_to_creator: creator_quote,
            quote_to_platform: platform_quote,
            base_to_creator: creator_base,
            base_to_platform: platform_base,
        });
        Ok(())
    }
}

// --- the curve itself ----------------------------------------------------------------------------

/// Pure arithmetic, kept out of the instruction bodies so it can be tested without a validator.
pub mod math {
    use super::{LaunchError, BPS};
    use anchor_lang::prelude::*;

    /// `bps` of `amount`, rounded down.
    pub fn bps_of(amount: u64, bps: u16) -> Result<u64> {
        let v = (amount as u128)
            .checked_mul(bps as u128)
            .ok_or(LaunchError::MathOverflow)?
            / BPS;
        u64::try_from(v).map_err(|_| LaunchError::MathOverflow.into())
    }

    /// One side of a constant-product swap: `reserve_out * amount_in / (reserve_in + amount_in)`.
    ///
    /// Rounded down, which is the direction that leaves the rounding dust in the curve rather than
    /// in the trader's pocket. Both legs use this, because a buy and a sell are the same trade read
    /// from opposite ends.
    pub fn swap_out(reserve_out: u128, reserve_in: u128, amount_in: u128) -> Result<u128> {
        let denominator = reserve_in
            .checked_add(amount_in)
            .ok_or(LaunchError::MathOverflow)?;
        require!(denominator > 0, LaunchError::MathOverflow);
        let numerator = reserve_out
            .checked_mul(amount_in)
            .ok_or(LaunchError::MathOverflow)?;
        Ok(numerator / denominator)
    }

    /// Work out what a buy actually costs, given how much room the curve has left.
    ///
    /// Returns `(quote_taken, fee, net)`: what leaves the buyer's account, what the platform keeps,
    /// and what reaches the reserve. When the curve is nearly full the whole triple shrinks so that
    /// `net` lands exactly on the remaining room, which is how a raise ends on its threshold rather
    /// than past it.
    pub fn split_buy(max_quote_in: u64, fee_bps: u16, room: u64) -> Result<(u64, u64, u64)> {
        let fee = bps_of(max_quote_in, fee_bps)?;
        let net = max_quote_in
            .checked_sub(fee)
            .ok_or(LaunchError::MathOverflow)?;
        if net <= room {
            return Ok((max_quote_in, fee, net));
        }

        // Scale the fee back to the part of the trade that is actually used. `fee_bps` is a share
        // of the gross, so the fee on a net of `room` is `room * bps / (BPS - bps)`.
        let denominator = BPS
            .checked_sub(fee_bps as u128)
            .ok_or(LaunchError::MathOverflow)?;
        require!(denominator > 0, LaunchError::MathOverflow);
        let fee = u64::try_from(
            (room as u128)
                .checked_mul(fee_bps as u128)
                .ok_or(LaunchError::MathOverflow)?
                / denominator,
        )
        .map_err(|_| LaunchError::MathOverflow)?;
        let taken = room.checked_add(fee).ok_or(LaunchError::MathOverflow)?;
        Ok((taken, fee, room))
    }

    /// The price the pool has to open at, as sqrt(quote per base) in Q64.64, which is how the pool
    /// program stores a price.
    ///
    /// `sqrt(q / b) * 2^64` is the same number as `sqrt((q << 64) / b) << 32`, and the second form
    /// stays inside a u128 for every amount this program can hold. The shift costs the low 32 bits of
    /// a 128-bit value, which is far below the precision any pool cares about.
    pub fn expected_sqrt_price(quote: u64, base: u64) -> Result<u128> {
        require!(quote > 0 && base > 0, LaunchError::ZeroAmount);
        let scaled = ((quote as u128) << 64) / (base as u128);
        Ok(isqrt(scaled) << 32)
    }

    /// Integer square root, by the usual bit-by-bit method. No floats in a program.
    pub fn isqrt(value: u128) -> u128 {
        if value < 2 {
            return value;
        }
        let mut bit = 1u128 << ((127 - value.leading_zeros()) & !1);
        let mut root = 0u128;
        let mut rest = value;
        while bit != 0 {
            let candidate = root + bit;
            root >>= 1;
            if rest >= candidate {
                rest -= candidate;
                root += bit;
            }
            bit >>= 2;
        }
        root
    }

    /// True when two prices are within one percent of each other, which is the slack the caller gets
    /// for its own rounding when it works out the pool's opening price.
    pub fn within_one_percent(a: u128, b: u128) -> bool {
        let (lo, hi) = if a < b { (a, b) } else { (b, a) };
        match hi.checked_sub(lo) {
            Some(gap) => gap.saturating_mul(100) <= hi,
            None => false,
        }
    }

    /// The transfer tax on an amount, rounded up, which is how Token-2022 computes it. The curve fee
    /// rounds down because it rounds in the curve's favour; a transfer fee is not ours to round.
    pub fn tax_of(amount: u64, bps: u16) -> Result<u64> {
        if bps == 0 || amount == 0 {
            return Ok(0);
        }
        let v = (amount as u128)
            .checked_mul(bps as u128)
            .ok_or(LaunchError::MathOverflow)?
            .div_ceil(BPS);
        u64::try_from(v).map_err(|_| LaunchError::MathOverflow.into())
    }

    /// What arrives when `amount` is sent and a transfer fee of `bps` is taken out of it on the way.
    pub fn net_of_tax(amount: u64, bps: u16) -> Result<u64> {
        let fee = tax_of(amount, bps)?;
        amount.checked_sub(fee).ok_or(LaunchError::MathOverflow.into())
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        /// The defaults this program is meant to launch with: 1B supply at 6 decimals, 80% of it on
        /// the curve, 1,000,000 COOK to graduate, and virtual reserves that make the price rise 16x
        /// from open to graduation.
        const SALE_BASE: u128 = 800_000_000_000_000; // 800M at 6 decimals
        const GRADUATION: u128 = 1_000_000_000_000_000; // 1M COOK at 9 decimals
        const VIRTUAL_QUOTE: u128 = GRADUATION / 3;
        const VIRTUAL_BASE: u128 = SALE_BASE * 4 / 3;

        fn buy(sold: u128, raised: u128, net: u128) -> u128 {
            swap_out(VIRTUAL_BASE - sold, VIRTUAL_QUOTE + raised, net).unwrap()
        }

        #[test]
        fn fee_is_a_share_of_the_gross() {
            assert_eq!(bps_of(1_000_000, 100).unwrap(), 10_000);
            assert_eq!(bps_of(1, 100).unwrap(), 0);
            assert_eq!(bps_of(u64::MAX, 0).unwrap(), 0);
        }

        #[test]
        fn the_whole_sale_supply_fits_in_the_raise() {
            // Selling into the curve until the threshold is reached must not need more base than
            // the curve has to sell, or a launch could hit its target with nothing left to deliver.
            let sold = buy(0, 0, GRADUATION);
            assert!(sold <= SALE_BASE, "sold {sold} > sale supply {SALE_BASE}");
            // and it should be close to the whole thing, or the curve stops early and burns most
            // of its supply
            assert!(sold * 100 / SALE_BASE >= 99, "only {} percent sold", sold * 100 / SALE_BASE);
        }

        #[test]
        fn price_rises_as_the_curve_fills() {
            let first = buy(0, 0, 1_000_000_000);
            let mid = buy(first, 1_000_000_000, 1_000_000_000);
            assert!(mid < first, "the second buy should get less base: {mid} vs {first}");
        }

        #[test]
        fn a_round_trip_never_profits() {
            // Buy, then immediately sell it all back with no fee at all. The invariant plus
            // rounding has to leave the trader with less quote than they put in, or the curve
            // leaks.
            let spent = 500_000_000_000_000u128;
            let got = buy(0, 0, spent);
            let back = swap_out(VIRTUAL_QUOTE + spent, VIRTUAL_BASE - got, got).unwrap();
            assert!(back <= spent, "round trip returned {back} for {spent}");
        }

        #[test]
        fn a_buy_is_clamped_to_the_room_left() {
            // 1% fee, and only 99 units of room: the net lands on the room exactly and the fee
            // shrinks with it.
            let (taken, fee, net) = split_buy(1_000_000, 100, 99).unwrap();
            assert_eq!(net, 99);
            assert_eq!(fee, 1);
            assert_eq!(taken, 100);
            assert!(taken <= 1_000_000);
        }

        #[test]
        fn an_unclamped_buy_keeps_the_whole_amount() {
            let (taken, fee, net) = split_buy(1_000_000, 100, u64::MAX).unwrap();
            assert_eq!(taken, 1_000_000);
            assert_eq!(fee, 10_000);
            assert_eq!(net, 990_000);
        }

        #[test]
        fn isqrt_is_a_square_root() {
            for v in [0u128, 1, 2, 3, 4, 9, 10, 1 << 64, u128::MAX] {
                let r = isqrt(v);
                assert!(r.saturating_mul(r) <= v, "isqrt({v}) = {r} is too big");
                let next = r + 1;
                assert!(
                    next.checked_mul(next).map(|sq| sq > v).unwrap_or(true),
                    "isqrt({v}) = {r} is too small"
                );
            }
        }

        #[test]
        fn the_pool_opens_where_the_curve_closed() {
            // A pool seeded with the reserve and the migration supply has to open at the curve's
            // closing price, or the first trade after graduation is free money.
            let quote = GRADUATION as u64;
            let base = 200_000_000_000_000u64; // 200M at 6 decimals
            let sqrt_price = expected_sqrt_price(quote, base).unwrap();
            // Square it back. Shifting a Q64.64 root down by 32 and squaring lands on the price in
            // Q64.64 again, which is the form the ratio below is already in.
            let price = (sqrt_price >> 32) * (sqrt_price >> 32);
            let expected = ((quote as u128) << 64) / base as u128;
            assert!(within_one_percent(price, expected), "{price} vs {expected}");
        }

        #[test]
        fn the_pool_is_priced_on_what_it_receives() {
            // A fully sold curve has exactly the migration supply left, so the pool can only ever
            // hold that minus the tax. Pricing it any other way asks the vault for base it does not
            // have.
            let migration = 200_000_000_000_000u64;
            let seeded = net_of_tax(migration, 300).unwrap();
            assert_eq!(seeded, 194_000_000_000_000);
            assert_eq!(net_of_tax(migration, 0).unwrap(), migration);
            // rounded up, like the token program: a single unit still owes a whole unit of tax
            assert_eq!(tax_of(1, 300).unwrap(), 1);
            assert_eq!(tax_of(0, 300).unwrap(), 0);
            assert_eq!(tax_of(u64::MAX, 10_000).unwrap(), u64::MAX);

            let taxed = expected_sqrt_price(GRADUATION as u64, seeded).unwrap();
            let untaxed = expected_sqrt_price(GRADUATION as u64, migration).unwrap();
            assert!(taxed > untaxed, "a taxed pool opens dearer per token");
        }

        #[test]
        fn one_percent_is_the_whole_slack() {
            assert!(within_one_percent(100, 100));
            assert!(within_one_percent(100, 101));
            assert!(!within_one_percent(100, 102));
            assert!(!within_one_percent(0, 1));
        }

        #[test]
        fn no_amount_the_chain_can_hold_overflows() {
            // Every amount on the way in is a u64, and u64::MAX squared still fits in a u128, so
            // the multiply inside swap_out cannot overflow for any input the chain can express.
            let max = u64::MAX as u128;
            assert!(swap_out(max, max, max).is_ok());
            assert!(bps_of(u64::MAX, 10_000).is_ok());
            // Beyond that it has to fail loudly rather than wrap.
            assert!(swap_out(u128::MAX, 1, u128::MAX).is_err());
        }
    }
}

